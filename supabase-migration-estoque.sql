-- O que isso faz: cria a tabela "estoque", que guarda a quantidade
-- disponível de cada produto (ex: Camiseta) por cor e tamanho —
-- a peça lisa, sem estampa (estampa é produzida sob demanda).
-- A saída do estoque é automática ao confirmar um Ganho com
-- cor/tamanho preenchidos, e volta automaticamente se o card for
-- reaberto ou se o ganho for editado. A entrada é sempre manual,
-- feita direto no CRM (aba Catálogo → botão "📦 Estoque" do produto).
-- ============================================================

create table if not exists public.estoque (
  id bigint generated by default as identity primary key,
  produto text not null,
  cor text not null,
  tamanho text not null,
  quantidade integer not null default 0,
  unique (produto, cor, tamanho)
);

alter table public.estoque enable row level security;

create policy "estoque_authenticated" on public.estoque for all to authenticated using (true) with check (true);

