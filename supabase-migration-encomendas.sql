--
-- O que isso faz: cria a tabela "encomendas", que guarda um registro
-- por item de camiseta (estampa+cor+tamanho) vendido em um Ganho.
-- É gerada automaticamente ao confirmar um ganho com itens que têm
-- cor e tamanho preenchidos (peça sob encomenda/produção, diferente
-- da peça lisa em estoque). O prazo padrão é de 2 dias úteis a
-- partir da data do pedido, mas pode ser editado no CRM.
--
-- A coluna "venda_id" identifica a qual Ganho (registro em neg_hist)
-- aquele item pertence — é usada para apagar as encomendas certas
-- automaticamente quando o card é reaberto (reabrirCard()), evitando
-- produzir peça de uma venda desfeita/dada por engano.
-- ============================================================

create table if not exists public.encomendas (
  id bigint generated by default as identity primary key,
  contato_id text not null,
  contato_nome text not null default '',
  venda_id text,
  produto text not null default '',
  estampa text not null default '',
  cor text not null default '',
  tamanho text not null default '',
  qty integer not null default 1,
  data_pedido date not null,
  prazo date not null,
  entregue boolean not null default false,
  data_entrega date,
  created_at timestamptz not null default now()
);

-- Caso a tabela já tenha sido criada antes desta coluna existir:
alter table public.encomendas add column if not exists venda_id text;

alter table public.encomendas enable row level security;

drop policy if exists "encomendas_authenticated" on public.encomendas;
create policy "encomendas_authenticated" on public.encomendas for all to authenticated using (true) with check (true);

