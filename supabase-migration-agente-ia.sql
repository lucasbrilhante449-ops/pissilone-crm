-- O que isso faz:
-- 1) Adiciona "foto_url" na tabela catalogo — usado só em itens
--    tipo='cor', pra guardar o link de uma foto de referência
--    daquela cor. O endpoint /estoque da Edge Function envia essa
--    foto direto no WhatsApp quando o cliente pergunta por um
--    tamanho.
-- 2) Cria "pedido_agente_pendente" — carrinho temporário do agente
--    de IA, por telefone, entre o momento em que ele vai listando
--    os itens da venda (via /adicionar-item-pedido) e o fechamento
--    (via /dar-ganho). Só a Edge Function acessa essa tabela
--    (service_role) — por isso não tem nenhuma policy de RLS pra
--    usuário autenticado, só RLS habilitado (bloqueia tudo por
--    padrão).
-- 3) Cria a função estoque_ajustar(), um upsert atômico
--    (insert ... on conflict ... do update quantidade = quantidade + delta)
--    pra evitar corrida quando duas vendas do agente mexem no
--    mesmo produto/cor/tamanho quase ao mesmo tempo.
-- ============================================================

alter table public.catalogo add column if not exists foto_url text;

create table if not exists public.pedido_agente_pendente (
  id bigint generated by default as identity primary key,
  telefone text not null,
  produto text not null default '',
  estampa text not null default '',
  cor text not null default '',
  tamanho text not null default '',
  qty integer not null default 1,
  criado_em timestamptz not null default now()
);

alter table public.pedido_agente_pendente enable row level security;
-- Sem policy nenhuma: só a Edge Function (service_role, que ignora RLS) acessa essa tabela.

create or replace function public.estoque_ajustar(p_produto text, p_cor text, p_tamanho text, p_delta integer)
returns void language sql as $$
  insert into public.estoque(produto,cor,tamanho,quantidade)
  values (p_produto,p_cor,p_tamanho,p_delta)
  on conflict (produto,cor,tamanho)
  do update set quantidade = estoque.quantidade + excluded.quantidade;
$$;

